"""Offline drift gate: the committed compatibility docs page vs the registry (D-07).

Checker independence (Phase 26 pattern): this gate re-implements the expected
row derivation from ``dnallm.models.registry`` accessors and never imports
anything from ``scripts/census_compat.py`` — the gate must not share the
generator's code, or generator drift would green itself. Fail-closed
(audit_skips posture): a missing page, a missing GENERATED header, or an
unparseable table is a test failure, never a skip.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from dnallm.models.registry import all_entries, sort_key_lab_first

DOCS_PAGE = Path(__file__).resolve().parents[2] / "docs" / "user_guide" / "model_compatibility.md"

GENERATED_HEADER = (
    "<!-- GENERATED by scripts/census_compat.py --emit-docs - DO NOT EDIT BY HAND -->"
)

# The transformers-4-side honesty wording, pinned verbatim including the
# Chinese original (D-05): the 4 side is inferred, never separately tested.
FOOTNOTE_INFERENCE = (
    "Transformers 4 compatibility is inferred - the model code was written in "
    "the transformers 4 era; no separate transformers 4 environment was tested. "
    # Fullwidth parens are verbatim owner-approved label text (D-05), not typos.
    "(推断兼容（模型代码写于 transformers 4 时代）)"  # ruff: ignore[ambiguous-unicode-character-string]
)

# An unqualified both-version claim is the one wording the page must never
# carry (Pitfall 8): the transformers 4 side is inferred, not tested.
FORBIDDEN_CLAIM = "compatible with transformers 4 and 5"

# The five pinned "What we found" wordings that need no evidence-derived
# continuation; broken/blocked cells append their derived cause/reason.
STATUS_CELLS = {
    "verified-tf5": "Tested working",
    "import-verified-tf5": "Tested loading its code; full run inferred from the family model",
    "shim-required-tf5": "Works with DNALLM's built-in compatibility fixes (tested)",
}


def _pretrained():
    """Return the pretrained registry entries (fail loudly when censused data is absent)."""
    entries = [entry for entry in all_entries() if entry.kind == "pretrained"]
    assert entries, "the packaged registry carries no pretrained entries"
    return entries


def _evidence_detail(evidence: str | None) -> str:
    """Return the evidence text after its ``hub repo@revision; `` stamp."""
    if not evidence:
        return ""
    head, sep, detail = evidence.partition("; ")
    return detail.strip() if sep else head.strip()


def _broken_cause(evidence: str | None) -> str:
    """Derive the broken-cause clause (first clause, failing-import prefix stripped).

    A bare single-symbol failing import prefers the following clause up to its
    first `` - `` boundary (it names what imports the missing symbol).
    """
    clauses = [clause.strip() for clause in _evidence_detail(evidence).split(";")]
    cause = clauses[0]
    prefix = "failing import: "
    if cause.startswith(prefix):
        cause = cause[len(prefix) :].strip()
        if cause and " " not in cause and len(clauses) > 1:
            cause = clauses[1].split(" - ")[0].strip()
    return cause


def _blocked_reason(evidence: str | None) -> str:
    """Derive the blocked reason clause (raw cache paths never reach the page)."""
    detail = _evidence_detail(evidence)
    if "unreachable on both hubs" in detail:
        return "its repository could not be reached on either download site"
    if "cannot read fetched config.json" in detail:
        return "its repository does not provide a usable configuration file at the top level"
    return detail.split(";")[0].strip()


def _expected_status_cell(entry) -> str:
    """Re-derive the expected "What we found" cell for one entry, independently."""
    status = entry.tf_compat_status
    if status is None:
        pytest.fail(
            f"registry entry {entry.model} carries no tf_compat_status (census data missing)"
        )
    if status in STATUS_CELLS:
        return STATUS_CELLS[status]
    if status == "remote-code-broken":
        cause = _broken_cause(entry.tf_compat_evidence)
        assert cause, f"broken entry {entry.model} carries no cause evidence"
        return f"Not usable with the current transformers - fails at {cause}"
    if status == "census-blocked":
        reason = _blocked_reason(entry.tf_compat_evidence)
        assert reason, f"blocked entry {entry.model} carries no reason evidence"
        return f"Could not be checked ({reason})"
    pytest.fail(f"unknown tf_compat_status {status!r} on {entry.model}")


def _expected_rows() -> list[tuple[str, str, str]]:
    """Re-derive the expected (name, status cell, representative-or-empty) rows.

    Ordering is lab-first via ``sort_key_lab_first`` — the page must list the
    ``zhangtaolab/`` models first (PFC-07 contract anchor).
    """
    rows: list[tuple[str, str, str]] = []
    for entry in sorted(_pretrained(), key=sort_key_lab_first):
        representative = ""
        if entry.tf_compat_status == "import-verified-tf5" and entry.tf_compat_evidence:
            match = re.search(r"family representative (\S+)", entry.tf_compat_evidence)
            if match:
                representative = match.group(1)
        rows.append((entry.name, _expected_status_cell(entry), representative))
    return rows


def _read_page() -> str:
    """Read the committed page, failing closed when it is absent."""
    if not DOCS_PAGE.is_file():
        pytest.fail(f"committed compatibility page is missing: {DOCS_PAGE}")
    return DOCS_PAGE.read_text(encoding="utf-8")


def _parse_table(page: str) -> tuple[list[tuple[str, str, str]], int]:
    """Parse the page's markdown table into (name, status, details) rows.

    Returns:
        The data rows (header and separator excluded) plus the 0-based line
        index of the last table line (the table region's end).

    Fails closed (pytest.fail, never a skip) when the table header, the
    separator, or any well-formed data row is missing, or a row does not
    carry exactly three cells.
    """
    lines = page.splitlines()
    starts = [i for i, line in enumerate(lines) if line.startswith("| Model |")]
    if not starts:
        pytest.fail("the compatibility page carries no '| Model |' table header")
    start = starts[0]
    if start + 1 >= len(lines) or not re.fullmatch(r"\| --- \| --- \| --- \|", lines[start + 1]):
        pytest.fail("the compatibility table carries no three-column separator row")
    rows: list[tuple[str, str, str]] = []
    end = start + 1
    for i in range(start + 2, len(lines)):
        if not lines[i].startswith("|"):
            break
        cells = [cell.strip() for cell in lines[i].strip().strip("|").split("|")]
        if len(cells) != 3:
            pytest.fail(f"unparseable table row ({len(cells)} cells): {lines[i]!r}")
        rows.append((cells[0], cells[1], cells[2]))
        end = i
    if not rows:
        pytest.fail("the compatibility table carries no data rows")
    return rows, end


def _tested_version() -> str:
    """Return the single distinct committed tested-transformers stamp."""
    tested = {entry.tf_compat_tested for entry in _pretrained() if entry.tf_compat_tested}
    if len(tested) != 1:
        pytest.fail(f"expected one committed tested version, got {sorted(tested)}")
    return next(iter(tested))


class TestPageContract:
    """Header, footnotes, and the both-version-claim prohibition (D-05 honesty)."""

    def test_generated_header_is_the_first_line(self):
        """The page opens with the exact GENERATED marker - hand edits are flagged."""
        page = _read_page()
        assert page.splitlines()[0] == GENERATED_HEADER

    def test_provenance_footnotes_verbatim_under_the_table(self):
        """Both footnotes appear verbatim (Chinese originals included), in order, under the table."""
        page = _read_page()
        version = _tested_version()
        footnote_1 = f"1. Tested on transformers {version}. (在 transformers {version} 上实测)"
        footnote_2 = f"2. {FOOTNOTE_INFERENCE}"
        _, table_end = _parse_table(page)
        index_1 = page.find(footnote_1)
        index_2 = page.find(footnote_2)
        assert index_1 != -1, f"tested-version footnote missing verbatim: {footnote_1!r}"
        assert index_2 != -1, f"inference footnote missing verbatim: {footnote_2!r}"
        table_offset = sum(len(line) + 1 for line in page.splitlines()[: table_end + 1])
        assert index_1 > table_offset, "the tested-version footnote must sit under the table"
        assert index_2 > index_1, "the inference footnote must follow the tested-version one"

    def test_no_unqualified_both_version_claim(self):
        """The table region never claims unqualified 4-and-5 compatibility."""
        page = _read_page()
        lines = page.splitlines()
        starts = [i for i, line in enumerate(lines) if line.startswith("| Model |")]
        assert starts, "table header missing"
        table_region = "\n".join(lines[starts[0] :])
        assert FORBIDDEN_CLAIM not in table_region


class TestRowsMatchRegistry:
    """Every table row is re-derived from the typed registry, independently."""

    def test_row_count_equals_registry_pretrained_count(self):
        """No stale extra rows after registry growth, no dropped rows."""
        rows, _ = _parse_table(_read_page())
        assert len(rows) == len(_pretrained())

    def test_page_order_is_lab_first(self):
        """The page lists the registry's lab-first order exactly (PFC-07)."""
        rows, _ = _parse_table(_read_page())
        expected_names = [row[0] for row in _expected_rows()]
        assert [row[0] for row in rows] == expected_names

    @pytest.mark.parametrize(
        ("name", "expected_status", "representative"),
        [pytest.param(name, status, rep, id=name) for name, status, rep in _expected_rows()],
    )
    def test_row_status_and_details_match_derivation(self, name, expected_status, representative):
        """Per row: present, status cell exactly the derived wording, Details non-empty."""
        rows, _ = _parse_table(_read_page())
        by_name = {row[0]: row for row in rows}
        assert name in by_name, f"model {name!r} missing from the compatibility table"
        _row_name, status, details = by_name[name]
        assert status == expected_status
        assert details, f"details cell for {name!r} is empty"
        if representative:
            assert representative in details, (
                f"import-verified row {name!r} must name its family representative "
                f"{representative!r} in the Details cell"
            )
